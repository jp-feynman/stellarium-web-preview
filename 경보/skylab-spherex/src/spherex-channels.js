export const CHANNELS = rows.map(([wavelength, detector, min, max], index) => ({ channel: index + 1, wavelength, detector, min, max }));
export const USABLE_CHANNELS = CHANNELS.filter((row) => !BLANK_CHANNELS.has(row.channel)).map((row) => row.channel);

export function isUsableChannel(channel) {
  return Number.isInteger(channel) && channel >= 1 && channel <= CHANNELS.length && !BLANK_CHANNELS.has(channel);
}

/** Upstream tile path inside the cube for a channel: frame 0 has no suffix, frame z has _z. */
export function cubeTileName(channel, pix) {
  return channel === 1 ? `Npix${pix}.png` : `Npix${pix}_${channel - 1}.png`;
}

export function formatWavelength(channel) {
  return CHANNELS[channel - 1].wavelength.toFixed(2);
}
