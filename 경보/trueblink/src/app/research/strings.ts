/** Translator signature shared by all components. */
export type Translate = (key: string) => string;

/** Default English translator (falls back to the key itself). */
export const tEn: Translate = (key: string) => (en as Record<string, string>)[key] ?? key;

/** Translator for a table, falling back to English then to the key. */
export function makeT(table: Record<string, string>): Translate {
  return (key: string) => table[key] ?? (en as Record<string, string>)[key] ?? key;
}
